/**
 * 洗牌发牌器:一轮之内不重复,发完再洗 —— 等候可能很短也可能很长,
 * 短的时候不能连着撞同一句,长的时候也不能发完就没了。
 */
export function createQuoteDeck(pool: MindfulQuote[] = MINDFUL_QUOTES) {
  let deck: MindfulQuote[] = [];
  let last: MindfulQuote | null = null;

  const refill = () => {
    deck = [...pool];
    for (let i = deck.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    // 新一轮的第一张与上一轮最后一张相同时,和第二张换个位置
    if (last && deck[0].text === last.text && deck.length > 1) [deck[0], deck[1]] = [deck[1], deck[0]];
  };

  return (): MindfulQuote => {
    if (deck.length === 0) refill();
    last = deck.pop()!;
    return last;
  };
}
